import {describe, it} from 'node:test'
import assert from 'node:assert/strict'
import {extractFingerprint, fingerprints, tagComment} from '../src/ghostfolio/fingerprint'
import {plan} from '../src/ghostfolio/sync'
import {GhostfolioClient} from '../src/ghostfolio/client'
import Ghostfolio, {GhostfolioActivity} from '../src/ghostfolio/mapper'
import {Transaction, TransactionType} from '../src/types'

const buy: Transaction = {
    type: TransactionType.BUY,
    ISIN: 'IE00B4L5Y983',
    quantity: 2,
    price: 85.12,
    currency: 'EUR',
    date: new Date('2024-03-15T00:00:00.000Z'),
    _meta: {provider: 'scalable-capital', file: '/somewhere/buy.pdf'},
}

describe('fingerprints', () => {
    it('are stable and independent of the file', () => {
        const [a] = fingerprints([buy])
        const [b] = fingerprints([{...buy, _meta: {provider: 'scalable-capital', file: '/elsewhere/copy.pdf'}}])
        assert.equal(a, b)
        assert.match(a, /^[0-9a-f]{16}$/)
    })

    it('change with any business field', () => {
        const [a] = fingerprints([buy])
        for (const change of [
            {quantity: 3},
            {price: 85.13},
            {currency: 'USD'},
            {type: TransactionType.SELL},
            {ISIN: 'X'},
        ])
            assert.notEqual(fingerprints([{...buy, ...change}])[0], a)
        assert.notEqual(fingerprints([{...buy, date: new Date('2024-03-16T00:00:00.000Z')}])[0], a)
    })

    it('keep identical transactions distinct but stable', () => {
        const [a, b] = fingerprints([buy, {...buy}])
        assert.notEqual(a, b)
        assert.deepEqual(fingerprints([buy, {...buy}]), [a, b])
        assert.equal(fingerprints([buy])[0], a)
    })

    it('round-trip through the comment', () => {
        const comment = tagComment('generated by ghostfolio-importer (v1)', 'abcdef0123456789')
        assert.equal(comment, 'generated by ghostfolio-importer (v1) [id:abcdef0123456789]')
        assert.equal(extractFingerprint(comment), 'abcdef0123456789')
        assert.equal(extractFingerprint('a manual note'), undefined)
        assert.equal(extractFingerprint(null), undefined)
    })

    it('are written into the activity comment by the mapper', () => {
        const ghost = new Ghostfolio({accountId: 'a', transactions: [buy], map: {IE00B4L5Y983: 'EUNL.DE'}})
        assert.equal(extractFingerprint(ghost.data.activities[0].comment), fingerprints([buy])[0])
    })
})

describe('sync plan', () => {
    const activity = (fingerprint: string): GhostfolioActivity => ({
        accountId: 'a',
        type: 'BUY',
        symbol: 'EUNL.DE',
        quantity: 1,
        unitPrice: 1,
        currency: 'EUR',
        date: '2024-01-01T00:00:00.000Z',
        fee: 0,
        dataSource: 'YAHOO',
        comment: tagComment('x', fingerprint),
    })
    const existing = (id: string, comment: string | null) => ({
        id,
        accountId: 'a',
        comment,
        date: '2024-01-01T00:00:00.000Z',
        type: 'BUY',
        quantity: 1,
        unitPrice: 1,
        currency: 'EUR',
    })

    it('creates missing, keeps present, flags stale, ignores manual activities', () => {
        const desired = [activity('1111111111111111'), activity('2222222222222222')]
        const inGhostfolio = [
            existing('e1', tagComment('x', '1111111111111111')),
            existing('e3', tagComment('x', '3333333333333333')),
            existing('e4', 'bought manually'),
            existing('e5', null),
        ]
        const result = plan(desired, inGhostfolio)
        assert.deepEqual(result.create, [desired[1]])
        assert.deepEqual(result.keep, [desired[0]])
        assert.deepEqual(
            result.stale.map(it => it.id),
            ['e3']
        )
    })

    it('is a no-op when everything is present', () => {
        const desired = [activity('1111111111111111')]
        const result = plan(desired, [existing('e1', tagComment('x', '1111111111111111'))])
        assert.equal(result.create.length, 0)
        assert.equal(result.stale.length, 0)
        assert.equal(result.keep.length, 1)
    })
})

describe('client base url', () => {
    it('accepts the origin or the import endpoint', () => {
        assert.equal(GhostfolioClient.baseUrlOf('http://localhost:3333'), 'http://localhost:3333')
        assert.equal(GhostfolioClient.baseUrlOf('http://localhost:3333/'), 'http://localhost:3333')
        assert.equal(GhostfolioClient.baseUrlOf('http://localhost:3333/api/v1/import'), 'http://localhost:3333')
        assert.equal(GhostfolioClient.baseUrlOf('https://ghostfol.io/api/v1/import/'), 'https://ghostfol.io')
    })
})
